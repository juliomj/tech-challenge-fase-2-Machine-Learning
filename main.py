"""Check that the prepared datasets produced by the DVC pipeline are usable."""

from purchase_propensity.data.loader import load_dataset
from purchase_propensity.data.schema import TARGET_COLUMN
from purchase_propensity.utils.config import CONFIG, PROJECT_ROOT
from purchase_propensity.utils.logger import get_logger


def main() -> None:
    """Load the prepared training and test datasets and log their shapes.

    Prepared datasets are generated by the DVC pipeline. This entry point
    consumes those artifacts without repeating data preparation.

    Raises:
        FileNotFoundError: If either prepared dataset is missing.
        ValueError: If either prepared dataset is empty.
    """
    logger = get_logger(__name__)
    prepared_path = PROJECT_ROOT / CONFIG["data"]["prepared_path"]

    train_data = load_dataset(prepared_path / CONFIG["data"]["train_dataset_file"])
    test_data = load_dataset(prepared_path / CONFIG["data"]["test_dataset_file"])

    logger.info(
        "Dados preparados carregados: %d linhas de treino, "
        "%d linhas de teste, %d features e target '%s'.",
        len(train_data),
        len(test_data),
        len(train_data.columns) - 1,
        TARGET_COLUMN,
    )


if __name__ == "__main__":
    main()
